                  la: SIMD3<Float> = .zero, ra: SIMD3<Float> = .zero,
                  ls: Float = 0, rs: Float = 0, lift: Float = 0, travel: Float = 0,
                  stance: Float = 0, bend: Float = 0, lc: Float = 0, rc: Float = 0) -> Pose {
