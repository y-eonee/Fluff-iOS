                        rightCheek: rightCheek * b + other.rightCheek * a,
                        hipSway: hipSway * b + other.hipSway * a,
                        leftReach: leftReach * b + other.leftReach * a,
                        rightReach: rightReach * b + other.rightReach * a)
        }
    }

