        var rightCheek: Float = 0
        var hipSway: Float = 0 // torso rotation around its upper attachment, radians
        var leftReach: Float = 0 // independent outward foot placement / doll height
        var rightReach: Float = 0

        func blended(to other: Pose, amount: Float) -> Pose {
            let a = min(1, max(0, amount)), b = 1 - a
