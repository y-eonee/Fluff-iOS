    static func sourcePose(at time: TimeInterval) -> Pose { sample(keyframes, at: time) }
    static func pose(at elapsed: TimeInterval) -> Pose { loop(keyframes, duration: duration, elapsed: elapsed) }

    static func sample(_ keys: [Keyframe], at elapsed: TimeInterval) -> Pose {
        guard elapsed.isFinite else { return keys[0].pose }
        let t = max(0, elapsed)
        guard let end = keys.firstIndex(where: { $0.time > t }) else { return keys.last!.pose }
        guard end > 0 else { return keys[0].pose }
        let a = keys[end - 1], b = keys[end]
        let x = Float((t - a.time) / (b.time - a.time))
        return a.pose.blended(to: b.pose, amount: x * x * (3 - 2 * x))
    }

    static func loop(_ keys: [Keyframe], duration: TimeInterval, elapsed: TimeInterval, reset: TimeInterval = resetDuration) -> Pose {
        guard elapsed.isFinite else { return keys[0].pose }
        let t = max(0, elapsed).truncatingRemainder(dividingBy: duration + reset)
        if t <= duration { return sample(keys, at: t) }
        let end = keys.last!.pose
        var start = keys[0].pose
        // The reset takes the shortest turn; it never rewrites the last source pose.
        while start.body.y - end.body.y > .pi { start.body.y -= 2 * .pi }
        while start.body.y - end.body.y < -.pi { start.body.y += 2 * .pi }
        let x = Float((t - duration) / reset)
        return end.blended(to: start, amount: x * x * (3 - 2 * x))
    }

