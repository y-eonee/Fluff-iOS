"""Generate Xcode colors and resource accessors from the verified Figma manifest."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "Malrang/Assets.xcassets"
MANIFEST = json.loads((ROOT / "design-tokens.json").read_text())
COLORS = MANIFEST["colors"]
COMPATIBILITY = MANIFEST["compatibilityColors"]


def write_color(name, token):
    directory = CATALOG / f"{name}.colorset"
    directory.mkdir(parents=True, exist_ok=True)
    rgba = token.get("rgba")
    if rgba:
        # Xcode interprets integer RGB strings as 0–255; normalized values need a decimal.
        components = {key: str(float(rgba[channel])) for key, channel in
                      (("red", "r"), ("green", "g"), ("blue", "b"), ("alpha", "a"))}
    else:
        value = token["value"]
        components = dict(zip(("red", "green", "blue"),
                              (f"0x{value[i:i + 2]}" for i in (1, 3, 5))))
        components["alpha"] = "1.000"
    contents = {"colors": [{"idiom": "universal", "color": {
        "color-space": "srgb", "components": components}}],
        "info": {"author": "xcode", "version": 1}}
    (directory / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")


def identifier(name):
    if name == "default":
        return "`default`"
    if name.isdigit():
        return "p" + name
    return re.sub(r"-([a-z])", lambda match: match[1].upper(), name)


def swift_members(tree, indent):
    lines = []
    for key, value in tree.items():
        if isinstance(value, dict):
            lines.append(f"{indent}enum {identifier(key)} {{")
            lines.extend(swift_members(value, indent + "    "))
            lines.append(f"{indent}}}")
        else:
            lines.append(f'{indent}static let {identifier(key)} = Color("{value}")')
    return lines


def resolved(token):
    return COLORS[token["alias"]] if "alias" in token else token


tree = {"rep4": {}, "mib": {}}
for name, token in COLORS.items():
    asset = f"Rep4/{name}"
    write_color(asset, token)
    tree["rep4"][name] = asset

for name, token in COMPATIBILITY.items():
    write_color("MIB/" + name, resolved(token))
    branch = tree["mib"]
    for part in name.split("/")[:-1]:
        branch = branch.setdefault(part, {})
    branch[name.split("/")[-1]] = "MIB/" + name

for root_name in ("MIB", "Rep4"):
    root = CATALOG / root_name
    for directory in [root, *(p for p in root.rglob("*") if p.is_dir())]:
        if directory.suffix == ".colorset":
            continue
        (directory / "Contents.json").write_text(json.dumps({
            "info": {"author": "xcode", "version": 1},
            "properties": {"provides-namespace": True}}, indent=2) + "\n")

for name, alias in MANIFEST["assetAliases"].items():
    write_color(name, resolved(COMPATIBILITY[alias]))

swift = ["// Generated by scripts/sync_color_tokens.py. Edit design-tokens.json.",
         "import SwiftUI", "", "extension Color {"]
swift.extend(swift_members(tree, "    "))
swift.extend(["}", ""])
(ROOT / "Malrang/DesignSystem/ColorTokens.swift").write_text("\n".join(swift))

# Bundle measured tokens without introducing view code or changing layouts.
(ROOT / "Malrang/Resources/RepresentativeDesign.json").write_text(
    json.dumps(MANIFEST, ensure_ascii=False, indent=2) + "\n")


def number(value):
    return format(value, ".17g")


def swift_color(rgba):
    return (f'Color(.sRGB, red: {number(rgba["r"])}, green: {number(rgba["g"])}, '
            f'blue: {number(rgba["b"])}, opacity: {number(rgba["a"])})')


definitions = [
    "// Generated by scripts/sync_color_tokens.py. Edit design-tokens.json.",
    "import SwiftUI", "",
    "struct RepresentativeGradient {",
    "    let stops: [Gradient.Stop]",
    "    let transform: [[Double]]",
    "    let opacity: Double",
    "}", "",
    "enum RepresentativeGradients {",
]
for name, token in MANIFEST["gradients"].items():
    stops = ", ".join(f'.init(color: {swift_color(s["color"])}, location: {number(s["position"])})'
                      for s in token["gradientStops"])
    matrix = json.dumps(token["gradientTransform"])
    definitions += [f'    static let {name} = RepresentativeGradient(',
                    f'        stops: [{stops}],',
                    f'        transform: {matrix}, opacity: {number(token["opacity"])})']
definitions += ["}", "", "struct RepresentativeTypographyToken {",
                "    let postScriptName: String", "    let size: CGFloat",
                "    let lineHeight: CGFloat?", "    let tracking: CGFloat",
                "    var font: Font { .custom(postScriptName, size: size, relativeTo: .body) }",
                "}", "", "enum RepresentativeTypography {"]
for name, token in MANIFEST["typography"].items():
    family = token["fontName"]["family"]
    style = token["fontName"]["style"]
    postscript = f"GmarketSansTTF{style}" if family == "Gmarket Sans TTF" else f"{family}-{style}"
    size = token["fontSize"]
    height = token["lineHeight"]
    line = (None if height["unit"] == "AUTO" else
            height["value"] * size / 100 if height["unit"] == "PERCENT" else height["value"])
    spacing = token["letterSpacing"]
    tracking = spacing["value"] * size / 100 if spacing["unit"] == "PERCENT" else spacing["value"]
    definitions += [f'    static let {name} = RepresentativeTypographyToken(',
                    f'        postScriptName: "{postscript}", size: {number(size)},',
                    f'        lineHeight: {"nil" if line is None else number(line)}, tracking: {number(tracking)})']
definitions += ["}", ""]
(ROOT / "Malrang/DesignSystem/RepresentativeTokens.swift").write_text("\n".join(definitions))
print(f"Generated {len(COLORS)} source colors, {len(COMPATIBILITY)} compatibility colors, "
      f"and {len(MANIFEST['assetAliases'])} named aliases.")
