"""Generate named Xcode colors and Swift accessors from the verified Figma palette."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "Malrang/Assets.xcassets"
MANIFEST = json.loads((ROOT / "design-tokens.json").read_text())
COLORS = MANIFEST["colors"]


def write_color(name, value):
    directory = CATALOG / f"{name}.colorset"
    directory.mkdir(parents=True, exist_ok=True)
    components = dict(zip(("red", "green", "blue"),
                          (f"0x{value[i:i + 2]}" for i in (1, 3, 5))))
    components["alpha"] = "1.000"
    contents = {"colors": [{"idiom": "universal", "color": {
        "color-space": "srgb", "components": components}}],
        "info": {"author": "xcode", "version": 1}}
    (directory / "Contents.json").write_text(json.dumps(contents, indent=2) + "\n")


def identifier(name):
    if name == "default":
        return "`default`"
    if name.isdigit():
        return "p" + name
    return re.sub(r"-([a-z])", lambda match: match[1].upper(), name)


def swift_members(tree, indent):
    lines = []
    for key, value in tree.items():
        if isinstance(value, dict):
            lines.append(f"{indent}enum {identifier(key)} {{")
            lines.extend(swift_members(value, indent + "    "))
            lines.append(f"{indent}}}")
        else:
            lines.append(f'{indent}static let {identifier(key)} = Color("MIB/{value}")')
    return lines


tree = {}
for name, token in COLORS.items():
    alias = token.get("alias")
    if alias:
        assert token["value"] == COLORS[alias]["value"], name
    write_color("MIB/" + name, token["value"])
    branch = tree
    for part in name.split("/")[:-1]:
        branch = branch.setdefault(part, {})
    branch[name.split("/")[-1]] = name

for directory in (CATALOG / "MIB").rglob("*"):
    if not directory.is_dir() or directory.suffix == ".colorset":
        continue
    (directory / "Contents.json").write_text(json.dumps({
        "info": {"author": "xcode", "version": 1},
        "properties": {"provides-namespace": True}}, indent=2) + "\n")
(CATALOG / "MIB/Contents.json").write_text(json.dumps({
    "info": {"author": "xcode", "version": 1},
    "properties": {"provides-namespace": True}}, indent=2) + "\n")

for name, alias in MANIFEST["assetAliases"].items():
    write_color(name, COLORS[alias]["value"])

swift = ["// Generated by scripts/sync_color_tokens.py. Edit design-tokens.json.",
         "import SwiftUI", "", "extension Color {", "    enum mib {"]
swift.extend(swift_members(tree, "        "))
swift.extend(["    }", "}", ""])
(ROOT / "Malrang/DesignSystem/ColorTokens.swift").write_text("\n".join(swift))
print(f"Generated {len(COLORS)} MIB colors and {len(MANIFEST['assetAliases'])} compatibility assets.")
